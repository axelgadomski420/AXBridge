use crate::axir::build::{Ir, IrNode, IrStmt};
use crate::error::AxResult;
use std::fmt::Write;
use std::path::Path;

/// Runtime documentu: natywne API DOM bez frameworka.
///
/// Generator `web` emituje komponenty React, więc wymaga `react` i `react-dom`
/// oraz kroku budowania. Ten generator produkuje `ax.app.js` w czystym JavaScripcie,
/// który przeglądarka wykonuje bezpośrednio — bez frameworka, bez bundlera i bez
/// zależności w `package.json`. To domyślna ścieżka dla `--target web`, dzięki
/// czemu `axc build` daje uruchamialną aplikację od razu.
pub struct DomReport {
    pub files: usize,
    pub unsupported: Vec<String>,
}

pub fn emit(ir: &Ir, out: &Path, _verbose: bool) -> AxResult<DomReport> {
    std::fs::create_dir_all(out)?;
    let mut report = DomReport { files: 0, unsupported: vec![] };

    let mut source = String::new();
    writeln!(source, "// Generated by AXCode — {} v{}", ir.app.name, ir.app.version).ok();
    writeln!(source, "// Runtime bez frameworka: natywne API DOM, ARIA i profil dostępności.").ok();
    writeln!(source, "\"use strict\";\n").ok();

    writeln!(source, "const app = {{").ok();
    writeln!(source, "  screen: null,").ok();
    writeln!(source, "  params: {{}},").ok();
    writeln!(source, "  a11y: {},", default_a11y_json()).ok();
    writeln!(source, "  user: null,").ok();
    writeln!(source, "  session: null,").ok();
    for global in &ir.globals {
        writeln!(source, "  {}: {},", global.name, js_default(&global.ty, &global.default)).ok();
    }
    writeln!(source, "  busy: false,").ok();
    writeln!(source, "  error: \"\",").ok();
    writeln!(source, "  toast: \"\"\n}};\n").ok();

    for store in &ir.stores {
        writeln!(source, "const {}Store = {{", store.name).ok();
        writeln!(source, "  key: {},", js_str(&store.key)).ok();
        writeln!(source, "  kind: {},", js_str(&store.kind)).ok();
        writeln!(source, "  encrypted: {},", store.encrypted).ok();
        writeln!(source, "  read() {{").ok();
        writeln!(source, "    try {{").ok();
        writeln!(source, "      const raw = localStorage.getItem(this.key);").ok();
        writeln!(source, "      if (!raw) return this.kind === \"list\" ? [] : null;").ok();
        writeln!(source, "      return JSON.parse(raw);").ok();
        writeln!(source, "    }} catch (error) {{").ok();
        writeln!(source, "      console.warn(\"Nie udało się odczytać {}\", error);", store.name).ok();
        writeln!(source, "      return this.kind === \"list\" ? [] : null;").ok();
        writeln!(source, "    }}\n  }},").ok();
        writeln!(source, "  write(value) {{").ok();
        writeln!(source, "    try {{").ok();
        writeln!(source, "      localStorage.setItem(this.key, JSON.stringify(value));").ok();
        writeln!(source, "      return true;").ok();
        writeln!(source, "    }} catch (error) {{").ok();
        writeln!(source, "      console.error(\"Nie udało się zapisać {}\", error);", store.name).ok();
        writeln!(source, "      return false;").ok();
        writeln!(source, "    }}\n  }},").ok();
        writeln!(source, "  clear() {{ localStorage.removeItem(this.key); }}\n}};\n").ok();
    }

    for function in &ir.functions {
        let params = function.params.iter().map(|(name, _)| name.clone()).collect::<Vec<_>>().join(", ");
        writeln!(source, "function {}({}) {{", function.name, params).ok();
        if function.body.is_empty() {
            writeln!(source, "  return undefined;").ok();
        }
        for stmt in &function.body {
            emit_stmt(&mut source, stmt, 1, &mut report)?;
        }
        writeln!(source, "}}\n").ok();
    }

    writeln!(source, "function announce(message, politeness) {{").ok();
    writeln!(source, "  if (!app.a11y.announceChanges) return;").ok();
    writeln!(source, "  let region = document.getElementById(\"ax-live\");").ok();
    writeln!(source, "  region.setAttribute(\"aria-live\", politeness || \"polite\");").ok();
    writeln!(source, "  region.textContent = \"\";").ok();
    writeln!(source, "  setTimeout(function () {{ region.textContent = message; }}, 40);\n}}\n").ok();
    writeln!(source, "function haptic(pattern) {{").ok();
    writeln!(source, "  if (!navigator.vibrate) return false;").ok();
    writeln!(source, "  const strength = 0.5 + (app.a11y.vibrationStrength || 0.7);").ok();
    writeln!(source, "  navigator.vibrate(pattern.map(function (value) {{ return Math.round(value * strength); }}));").ok();
    writeln!(source, "  return true;\n}}\n").ok();
    writeln!(source, "function speak(text) {{").ok();
    writeln!(source, "  if (typeof speechSynthesis === \"undefined\") throw new Error(\"Synteza mowy niedostępna\");").ok();
    writeln!(source, "  const utterance = new SpeechSynthesisUtterance(text);").ok();
    writeln!(source, "  utterance.rate = Math.min(3, Math.max(0.5, app.a11y.ttsRate || 1));").ok();
    writeln!(source, "  utterance.pitch = Math.min(2, Math.max(0, app.a11y.ttsPitch || 1));").ok();
    writeln!(source, "  const voice = speechSynthesis.getVoices().find(function (candidate) {{ return candidate.name === app.a11y.ttsVoice; }});").ok();
    writeln!(source, "  if (voice) utterance.voice = voice;").ok();
    writeln!(source, "  speechSynthesis.speak(utterance);").ok();
    writeln!(source, "  return true;\n}}\n").ok();
    writeln!(source, "function applyAccessibilityProfile(profile) {{").ok();
    writeln!(source, "  Object.assign(app.a11y, profile || {{}});").ok();
    writeln!(source, "  const root = document.documentElement;").ok();
    writeln!(source, "  root.style.setProperty(\"--scale\", String(app.a11y.textScale || 1));").ok();
    writeln!(source, "  root.dataset.reduceMotion = String(!!app.a11y.reduceMotion);").ok();
    writeln!(source, "  root.dataset.contrast = app.a11y.highContrast ? \"high\" : \"normal\";\n}}\n").ok();
    writeln!(source, "function toast(message) {{").ok();
    writeln!(source, "  app.toast = message;").ok();
    writeln!(source, "  render();").ok();
    writeln!(source, "  announce(message);").ok();
    writeln!(source, "  window.setTimeout(function () {{ app.toast = \"\"; render(); }}, 2500);\n}}\n").ok();
    writeln!(source, "async function api(path, options) {{").ok();
    writeln!(source, "  const init = options || {{}};").ok();
    writeln!(source, "  const controller = new AbortController();").ok();
    writeln!(source, "  const timer = setTimeout(function () {{ controller.abort(); }}, init.timeout || 15000);").ok();
    writeln!(source, "  try {{").ok();
    writeln!(source, "    const headers = Object.assign({{ \"Content-Type\": \"application/json\" }}, init.headers || {{}});").ok();
    writeln!(source, "    if (app.session && app.session.accessToken) headers.Authorization = \"Bearer \" + app.session.accessToken;").ok();
    writeln!(source, "    const response = await fetch(path, {{ method: init.method || \"GET\", headers: headers, body: init.body ? JSON.stringify(init.body) : undefined, signal: controller.signal }});").ok();
    writeln!(source, "    if (!response.ok) {{").ok();
    writeln!(source, "      const payload = await response.json().catch(function () {{ return {{}}; }});").ok();
    writeln!(source, "      throw new Error((payload.error && payload.error.message) || \"HTTP \" + response.status);").ok();
    writeln!(source, "    }}").ok();
    writeln!(source, "    if (response.status === 204) return null;").ok();
    writeln!(source, "    return await response.json();").ok();
    writeln!(source, "  }} finally {{ clearTimeout(timer); }}\n}}\n").ok();

    writeln!(source, "const screens = {{}};").ok();
    writeln!(source, "const screenOrder = [{}];", ir.screens.iter().map(|s| js_str(&s.name)).collect::<Vec<_>>().join(", ")).ok();
    writeln!(source, "const screenTitles = {{").ok();
    for screen in &ir.screens {
        writeln!(source, "  {}: {},", screen.name, js_str(screen.title.as_deref().unwrap_or(&screen.name))).ok();
    }
    writeln!(source, "}};\n").ok();
    writeln!(source, "function navigate(name) {{").ok();
    writeln!(source, "  if (name === \"__back\") {{").ok();
    writeln!(source, "    const index = screenOrder.indexOf(app.screen);").ok();
    writeln!(source, "    name = screenOrder[Math.max(0, index - 1)];").ok();
    writeln!(source, "  }}").ok();
    writeln!(source, "  if (!screens[name]) {{ app.error = \"Nieznany ekran: \" + name; render(); return; }}").ok();
    writeln!(source, "  app.screen = name;").ok();
    writeln!(source, "  app.error = \"\";").ok();
    writeln!(source, "  render();").ok();
    writeln!(source, "  const heading = document.getElementById(\"ax-heading\");").ok();
    writeln!(source, "  if (heading) heading.focus();").ok();
    writeln!(source, "  announce((screenTitles[name] || name) + \", ekran otwarty\");\n}}\n").ok();

    for screen in &ir.screens {
        writeln!(source, "screens[{}] = function () {{", js_str(&screen.name)).ok();
        writeln!(source, "  const h = [];").ok();
        for (name, ty, default) in &screen.states {
            writeln!(source, "  let {} = app[{}] !== undefined ? app[{}] : {};", name, js_str(name), js_str(name), js_default(ty, default)).ok();
        }
        for node in &screen.nodes {
            emit_node(&mut source, node, 1, &mut report)?;
        }
        writeln!(source, "  return h.join(\"\");\n}};\n").ok();
    }

    writeln!(source, "function render() {{").ok();
    writeln!(source, "  const root = document.getElementById(\"ax-root\");").ok();
    writeln!(source, "  if (!root) return;").ok();
    writeln!(source, "  const name = app.screen || screenOrder[0];").ok();
    writeln!(source, "  const title = screenTitles[name] || name;").ok();
    writeln!(source, "  const body = screens[name] ? screens[name]() : \"\";").ok();
    writeln!(source, "  root.innerHTML =").ok();
    writeln!(source, "    \"<main class=\\\"screen\\\">\" +").ok();
    writeln!(source, "    \"  <h1 id=\\\"ax-heading\\\" tabindex=\\\"-1\\\">\" + escapeHtml(title) + \"</h1>\" +").ok();
    writeln!(source, "    (app.error ? \"  <p class=\\\"alert\\\" role=\\\"alert\\\">\" + escapeHtml(app.error) + \"</p>\" : \"\") +").ok();
    writeln!(source, "    (app.toast ? \"  <p class=\\\"caption\\\" role=\\\"status\\\">\" + escapeHtml(app.toast) + \"</p>\" : \"\") +").ok();
    writeln!(source, "    body +").ok();
    writeln!(source, "    \"  <nav class=\\\"caption\\\" aria-label=\\\"Nawigacja główna\\\">\" +").ok();
    writeln!(source, "    screenOrder.map(function (item) {{").ok();
    writeln!(source, "      const active = item === name ? \" aria-current=\\\"page\\\"\" : \"\";").ok();
    writeln!(source, "      return \"<button type=\\\"button\\\" data-nav=\\\"\" + escapeHtml(item) + \"\\\"\" + active + \">\" + escapeHtml(screenTitles[item] || item) + \"</button>\";").ok();
    writeln!(source, "    }}).join(\"\") +").ok();
    writeln!(source, "    \"  </nav>\" +").ok();
    writeln!(source, "    \"</main>\";").ok();
    writeln!(source, "  root.querySelectorAll(\"[data-nav]\").forEach(function (element) {{").ok();
    writeln!(source, "    element.addEventListener(\"click\", function () {{ navigate(element.getAttribute(\"data-nav\")); }});").ok();
    writeln!(source, "  }});").ok();
    writeln!(source, "  root.querySelectorAll(\"[data-action]\").forEach(function (element) {{").ok();
    writeln!(source, "    element.addEventListener(\"click\", function () {{").ok();
    writeln!(source, "      const action = element.getAttribute(\"data-action\");").ok();
    writeln!(source, "      if (typeof window.axActions[action] === \"function\") {{").ok();
    writeln!(source, "        try {{ window.axActions[action](); }} catch (error) {{ app.error = String(error.message || error); render(); }}").ok();
    writeln!(source, "      }}").ok();
    writeln!(source, "    }});").ok();
    writeln!(source, "  }});\n}}\n").ok();
    writeln!(source, "function escapeHtml(value) {{").ok();
    writeln!(source, "  return String(value).replace(/&/g, \"&amp;\").replace(/</g, \"&lt;\").replace(/>/g, \"&gt;\").replace(/\"/g, \"&quot;\");\n}}\n").ok();

    writeln!(source, "window.axActions = {{}};").ok();
    let mut action_index = 0;
    for screen in &ir.screens {
        for node in &screen.nodes {
            emit_actions(&mut source, node, &mut action_index, &mut report)?;
        }
    }

    writeln!(source, "function boot() {{").ok();
    writeln!(source, "  applyAccessibilityProfile(null);").ok();
    writeln!(source, "  app.screen = screenOrder[0];").ok();
    writeln!(source, "  render();").ok();
    writeln!(source, "  window.addEventListener(\"online\", function () {{ announce(\"Połączenie przywrócone\"); }});").ok();
    writeln!(source, "  window.addEventListener(\"offline\", function () {{ announce(\"Brak połączenia. Kolejka offline zapisuje wiadomości.\", \"assertive\"); }});\n}}\n").ok();
    writeln!(source, "if (document.readyState === \"loading\") {{").ok();
    writeln!(source, "  document.addEventListener(\"DOMContentLoaded\", boot);").ok();
    writeln!(source, "}} else {{").ok();
    writeln!(source, "  boot();").ok();
    writeln!(source, "}}\n").ok();
    writeln!(source, "export {{ app, navigate, render, announce, api, haptic, speak, applyAccessibilityProfile, toast }};").ok();

    std::fs::write(out.join("ax.app.js"), source)?;
    report.files += 1;

    let shell = include_str!("templates/accessible-shell.html")
        .replace("{{APP_NAME}}", &ir.app.name)
        .replace("{{LANG}}", &ir.app.language)
        .replace("{{TEXT_SCALE}}", &format!("{}", ir.app.text_scale))
        .replace("{%ROOT_ATTRS%}", "")
        .replace("{%ROOT_STYLE%}", "");
    std::fs::write(out.join("index.html"), shell)?;
    report.files += 1;

    Ok(report)
}

fn emit_node(source: &mut String, node: &crate::axir::IrNode, depth: usize, report: &mut DomReport) -> AxResult<()> {
    let pad = "  ".repeat(depth);
    let label = node
        .accessibility_label
        .clone()
        .or_else(|| node.label.clone())
        .or_else(|| node.alt.clone());

    match node.kind.as_str() {
        "column" | "row" => {
            let role = if node.kind == "row" { "group" } else { "region" };
            writeln!(source, "{pad}h.push(\"<div role=\\\"{}\\\" class=\\\"card\\\">\");", role).ok();
            for child in &node.children {
                emit_node(source, child, depth, report)?;
            }
            writeln!(source, "{pad}h.push(\"</div>\");").ok();
        }
        "list" => {
            let live = node.aria_live.clone().unwrap_or_else(|| "polite".into());
            writeln!(source, "{pad}h.push(\"<ul role=\\\"list\\\" aria-live=\\\"{}\\\">\");", live).ok();
            for child in &node.children {
                emit_node(source, child, depth, report)?;
            }
            writeln!(source, "{pad}h.push(\"</ul>\");").ok();
        }
        "item" => {
            writeln!(source, "{pad}h.push(\"<li>\");").ok();
            for child in &node.children {
                emit_node(source, child, depth, report)?;
            }
            writeln!(source, "{pad}h.push(\"</li>\");").ok();
        }
        "text" => {
            let body = node.label.clone().unwrap_or_default();
            let aria = label
                .as_ref()
                .filter(|value| **value != body)
                .map(|value| format!(" aria-label=\\\"{}\\\"", escape_attr(value)))
                .unwrap_or_default();
            writeln!(source, "{pad}h.push(\"<p{}>{}</p>\");", aria, escape_source(&body)).ok();
        }
        "button" => {
            let body = node.label.clone().unwrap_or_else(|| "Przycisk".into());
            let aria = label
                .as_ref()
                .map(|value| format!(" aria-label=\\\"{}\\\"", escape_attr(value)))
                .unwrap_or_default();
            let height = node.height.unwrap_or(48.0);
            let action = action_for(node).unwrap_or_default();
            if action.is_empty() {
                writeln!(source, "{pad}h.push(\"<button type=\\\"button\\\" disabled{} style=\\\"min-height:{}px\\\">{}</button>\");", aria, height, escape_source(&body)).ok();
                report.unsupported.push("button-without-action".into());
            } else {
                writeln!(source, "{pad}h.push(\"<button type=\\\"button\\\" data-action=\\\"{}\\\"{} style=\\\"min-height:{}px\\\">{}</button>\");", action, aria, height, escape_source(&body)).ok();
            }
        }
        "image" => {
            let alt = node.alt.clone().unwrap_or_default();
            writeln!(source, "{pad}h.push(\"<p role=\\\"img\\\" aria-label=\\\"{}\\\">🖼️</p>\");", escape_attr(&alt)).ok();
        }
        "video" => {
            let alt = node.alt.clone().unwrap_or_default();
            let captions = node.props.iter().any(|(key, _)| key == "captions");
            let note = if captions { "Wideo z napisami" } else { "Wideo bez napisów" };
            writeln!(source, "{pad}h.push(\"<div role=\\\"group\\\" aria-label=\\\"{}\\\"><p class=\\\"caption\\\">{}</p></div>\");", escape_attr(&alt), note).ok();
        }
        "toggle" => {
            let body = node.label.clone().unwrap_or_else(|| "Przełącznik".into());
            writeln!(source, "{pad}h.push(\"<button type=\\\"button\\\" role=\\\"switch\\\" aria-checked=\\\"false\\\" aria-label=\\\"{}\\\" style=\\\"min-height:48px\\\">{}</button>\");", escape_attr(&body), escape_source(&body)).ok();
        }
        "slider" => {
            let body = node.label.clone().unwrap_or_else(|| "Suwak".into());
            writeln!(source, "{pad}h.push(\"<label>{}</label><input type=\\\"range\\\" min=\\\"0\\\" max=\\\"100\\\" aria-label=\\\"{}\\\">\");", escape_source(&body), escape_attr(&body)).ok();
            report.unsupported.push("slider-binding".into());
        }
        "field" => {
            let body = node.label.clone().unwrap_or_else(|| "Pole".into());
            writeln!(source, "{pad}h.push(\"<label>{}</label><input type=\\\"text\\\" aria-label=\\\"{}\\\">\");", escape_source(&body), escape_attr(&body)).ok();
            report.unsupported.push("field-binding".into());
        }
        "confirm" => {
            writeln!(source, "{pad}h.push(\"<section role=\\\"alertdialog\\\" aria-modal=\\\"false\\\"{}>\");", label.map(|value| format!(" aria-label=\\\"{}\\\"", escape_attr(&value))).unwrap_or_default()).ok();
            for child in &node.children {
                emit_node(source, child, depth, report)?;
            }
            writeln!(source, "{pad}h.push(\"<p class=\\\"caption\\\">Wymaga zatwierdzenia przez człowieka.</p></section>\");").ok();
        }
        "timer" => {
            writeln!(source, "{pad}// timer obsługiwany przez zdarzenia przeglądarki").ok();
        }
        other => report.unsupported.push(other.to_string()),
    }
    Ok(())
}

fn action_for(node: &crate::axir::IrNode) -> Option<String> {
    node.on_tap.iter().find_map(|stmt| match stmt {
        crate::axir::IrStmt::Go { screen } => Some(format!("go:{}", screen)),
        crate::axir::IrStmt::Toast(expr) => Some(format!("toast:{}", expr_text(expr))),
        crate::axir::IrStmt::Api { path, .. } => Some(format!("api:{}", path)),
        crate::axir::IrStmt::CallFn { name, .. } => Some(format!("call:{}", name)),
        _ => None,
    })
}

fn emit_actions(source: &mut String, node: &crate::axir::IrNode, index: &mut usize, report: &mut DomReport) -> AxResult<()> {
    if let Some(action) = action_for(node) {
        *index += 1;
        writeln!(source, "window.axActions[{}] = function () {{", js_str(&action)).ok();
        for stmt in &node.on_tap {
            emit_stmt(source, stmt, 1, report)?;
        }
        writeln!(source, "}};\n").ok();
    }
    for child in &node.children {
        emit_actions(source, child, index, report)?;
    }
    Ok(())
}

fn emit_stmt(source: &mut String, stmt: &crate::axir::IrStmt, depth: usize, report: &mut DomReport) -> AxResult<()> {
    let pad = "  ".repeat(depth);
    match stmt {
        crate::axir::IrStmt::Set { target, value } => {
            writeln!(source, "{pad}app[{}] = {};", js_str(target), expr_js(value)).ok();
        }
        crate::axir::IrStmt::Save { target } => {
            writeln!(source, "{pad}{}Store.write(app[{}]);", target, js_str(target)).ok();
        }
        crate::axir::IrStmt::Load { target } => {
            writeln!(source, "{pad}app[{}] = {}Store.read();", js_str(target), target).ok();
        }
        crate::axir::IrStmt::Go { screen } => {
            writeln!(source, "{pad}navigate({});", js_str(screen)).ok();
        }
        crate::axir::IrStmt::GoBack => {
            writeln!(source, "{pad}navigate(\"__back\");").ok();
        }
        crate::axir::IrStmt::Toast(expr) => {
            writeln!(source, "{pad}toast({});", expr_js(expr)).ok();
        }
        crate::axir::IrStmt::Alert(expr) => {
            writeln!(source, "{pad}window.alert({});", expr_js(expr)).ok();
        }
        crate::axir::IrStmt::Api { path, method, on_success, on_error } => {
            writeln!(source, "{pad}api({}, {{ method: {} }}).then(function () {{", js_str(path), js_str(method)).ok();
            for inner in on_success {
                emit_stmt(source, inner, depth + 1, report)?;
            }
            writeln!(source, "{pad}}})").ok();
            writeln!(source, "{pad}  .catch(function (error) {{").ok();
            writeln!(source, "{pad}    app.error = String(error.message || error);").ok();
            for inner in on_error {
                emit_stmt(source, inner, depth + 2, report)?;
            }
            writeln!(source, "{pad}    render();").ok();
            writeln!(source, "{pad}  }});").ok();
        }
        crate::axir::IrStmt::CallFn { name, args } => {
            let rendered = args.iter().map(expr_js).collect::<Vec<_>>().join(", ");
            writeln!(source, "{pad}void {}({});", name, rendered).ok();
        }
        crate::axir::IrStmt::If { cond, then, els } => {
            writeln!(source, "{pad}if ({}) {{", expr_js(cond)).ok();
            for inner in then {
                emit_stmt(source, inner, depth + 1, report)?;
            }
            if els.is_empty() {
                writeln!(source, "{pad}}}").ok();
            } else {
                writeln!(source, "{pad}}} else {{").ok();
                for inner in els {
                    emit_stmt(source, inner, depth + 1, report)?;
                }
                writeln!(source, "{pad}}}").ok();
            }
        }
        crate::axir::IrStmt::ForEach { var, iter, body } => {
            writeln!(source, "{pad}for (const {} of {}) {{", var, expr_js(iter)).ok();
            for inner in body {
                emit_stmt(source, inner, depth + 1, report)?;
            }
            writeln!(source, "{pad}}}").ok();
        }
        crate::axir::IrStmt::Add { target, value } => {
            writeln!(source, "{pad}(app[{}] || (app[{}] = [])).push({});", js_str(target), js_str(target), expr_js(value)).ok();
        }
        crate::axir::IrStmt::Remove { target, value } => {
            writeln!(source, "{pad}app[{}] = (app[{}] || []).filter(function (item) {{ return item !== {}; }});", js_str(target), js_str(target), expr_js(value)).ok();
        }
        crate::axir::IrStmt::Return(Some(expr)) => {
            writeln!(source, "{pad}return {};", expr_js(expr)).ok();
        }
        crate::axir::IrStmt::Return(None) => {}
    }
    Ok(())
}

fn expr_js(expr: &crate::ast::Expr) -> String {
    use crate::ast::{BinOp, Expr};
    match expr {
        Expr::Str(value) => js_str(value),
        Expr::Num(value) => format!("{}", value),
        Expr::Bool(value) => format!("{}", value),
        Expr::Ident(name) => format!("app[{}]", js_str(name)),
        Expr::Field(base, field) => format!("{}.{}", expr_js(base), field),
        Expr::Call(base, args) => format!("{}({})", expr_js(base), args.iter().map(expr_js).collect::<Vec<_>>().join(", ")),
        Expr::BinOp(left, op, right) => {
            let symbol = match op {
                BinOp::Add => "+", BinOp::Sub => "-", BinOp::Mul => "*", BinOp::Div => "/",
                BinOp::Eq => "===", BinOp::Ne => "!==", BinOp::Lt => "<", BinOp::Le => "<=",
                BinOp::Gt => ">", BinOp::Ge => ">=", BinOp::And => "&&", BinOp::Or => "||",
            };
            format!("({} {} {})", expr_js(left), symbol, expr_js(right))
        }
        Expr::UnOp(op, inner) => match op {
            crate::ast::UnOp::Not => format!("(!{})", expr_js(inner)),
            crate::ast::UnOp::Neg => format!("(-{})", expr_js(inner)),
        },
        Expr::Constructor { fields, .. } => {
            let pairs = fields.iter().map(|(key, value)| format!("{}: {}", js_str(key), expr_js(value))).collect::<Vec<_>>().join(", ");
            format!("{{ {} }}", pairs)
        }
        Expr::None => "null".into(),
    }
}

fn expr_text(expr: &crate::ast::Expr) -> String {
    match expr {
        crate::ast::Expr::Str(value) => value.clone(),
        crate::ast::Expr::Ident(name) => name.clone(),
        _ => "action".into(),
    }
}

fn js_default(ty: &str, default: &str) -> String {
    match ty {
        "Number" => default.parse::<f64>().map(|value| format!("{}", value)).unwrap_or_else(|_| "0".into()),
        "Boolean" => if default == "true" { "true".into() } else { "false".into() },
        "Text" => js_str(default.trim_matches('"')),
        "Date" | "Json" => "null".into(),
        other if other.starts_with("List<") => "[]".into(),
        other if other.starts_with("Map<") => "{}".into(),
        _ => "null".into(),
    }
}

