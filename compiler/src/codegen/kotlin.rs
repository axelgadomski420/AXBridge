use crate::axir::Ir;
use crate::error::AxResult;
use std::fmt::Write;
use std::path::Path;

pub fn emit(ir: &Ir, out: &Path, _verbose: bool) -> AxResult<()> {
    let mut s = String::new();
    writeln!(s, "// Generated by AXCode Ultra Compiler").ok();
    writeln!(s, "// App: {} v{}", ir.app.name, ir.app.version).ok();
    writeln!(s, "package com.axbridge\n").ok();
    writeln!(s, "import androidx.compose.runtime.*").ok();
    writeln!(s, "import androidx.compose.material3.*").ok();
    writeln!(s, "import androidx.compose.foundation.layout.*").ok();
    writeln!(s, "import androidx.compose.ui.Modifier\n").ok();

    for m in &ir.models {
        writeln!(s, "data class {}(", m.name).ok();
        for (i, f) in m.fields.iter().enumerate() {
            let comma = if i + 1 < m.fields.len() { "," } else { "" };
            writeln!(s, "    val {}: {}{}", f.name, kotlin_type(&f.ty), comma).ok();
        }
        writeln!(s, ")\n").ok();
    }

    for f in &ir.functions {
        let params = f.params.iter().map(|p| format!("{}: {}", p.name, kotlin_type(&p.ty))).collect::<Vec<_>>().join(", ");
        let ret = f.ret.as_ref().map(|t| format!(": {}", kotlin_type(t))).unwrap_or_default();
        writeln!(s, "fun {}({}){} {{", f.name, params, ret).ok();
        for st in &f.body {
            if let crate::ast::Stmt::Set { target, value } = st {
                writeln!(s, "    {} = {}", target, expr_str(value)).ok();
            }
        }
        writeln!(s, "}}\n").ok();
    }

    for sc in &ir.screens {
        writeln!(s, "@Composable").ok();
        writeln!(s, "fun {}Screen() {{", sc.name).ok();
        for st in &sc.states {
            writeln!(s, "    var {} by remember {{ mutableStateOf({}) }}", st.name, kotlin_default(&st.ty, &st.default)).ok();
        }
        writeln!(s, "    Column(modifier = Modifier.padding(16.dp)) {{").ok();
        for n in &sc.body { emit_ui_node(&mut s, n, 2); }
        writeln!(s, "    }}").ok();
        writeln!(s, "}}\n").ok();
    }

    std::fs::write(out.join("AXBridge.kt"), s)?;
    Ok(())
}

fn emit_ui_node(s: &mut String, n: &crate::ast::Node, depth: usize) {
    let pad = "    ".repeat(depth);
    match n.kind.as_str() {
        "text" => {
            let label = n.attrs.iter().find_map(|(k, v)| if k == "label" { if let crate::ast::PropValue::Str(s) = v { Some(s.clone()) } else { None } } else { None }).unwrap_or_default();
            writeln!(s, "{}Text(\"{}\")", pad, escape(&label)).ok();
        }
        "button" => {
            let label = n.attrs.iter().find_map(|(k, v)| if k == "label" { if let crate::ast::PropValue::Str(s) = v { Some(s.clone()) } else { None } } else { None }).unwrap_or_default();
            writeln!(s, "{}Button(onClick = {{}}, modifier = Modifier.sizeIn(minWidth = 48.dp, minHeight = 48.dp)) {{ Text(\"{}\") }}", pad, escape(&label)).ok();
        }
        "column" => {
            writeln!(s, "{}Column {{", pad).ok();
            for c in &n.children { emit_ui_node(s, c, depth + 1); }
            writeln!(s, "{}}}", pad).ok();
        }
        "row" => {
            writeln!(s, "{}Row {{", pad).ok();
            for c in &n.children { emit_ui_node(s, c, depth + 1); }
            writeln!(s, "{}}}", pad).ok();
        }
        "field" => {
            writeln!(s, "{}OutlinedTextField(value = \"\", onValueChange = {{}}, modifier = Modifier.fillMaxWidth())", pad).ok();
        }
        "spinner" => writeln!(s, "{}CircularProgressIndicator()", pad).ok(),
        "divider" => writeln!(s, "{}Divider()", pad).ok(),
        other => { writeln!(s, "{}// TODO: {}", pad, other).ok(); }
    }
}

fn kotlin_type(t: &crate::ast::TypeRef) -> String {
    use crate::ast::TypeRef::*;
    match t {
        Text => "String".into(),
        Number => "Double".into(),
        Boolean => "Boolean".into(),
        Date => "Long".into(),
        Json => "Map<String, Any>".into(),
        List(inner) => format!("List<{}>", kotlin_type(inner)),
        Map(inner) => format!("Map<String, {}>", kotlin_type(inner)),
        Optional(inner) => format!("{}?", kotlin_type(inner)),
        Named(n) => n.clone(),
    }
}

fn kotlin_default(t: &crate::ast::TypeRef, d: &str) -> String {
    if !d.is_empty() { return d.into(); }
    use crate::ast::TypeRef::*;
    match t {
        Text => "\"\"".into(),
        Number => "0.0".into(),
        Boolean => "false".into(),
        Optional(_) => "null".into(),
        List(_) => "emptyList()".into(),
        _ => "0L".into(),
    }
}

fn expr_str(e: &crate::ast::Expr) -> String {
    use crate::ast::Expr::*;
    match e {
        Str(s) => format!("\"{}\"", s),
        Num(n) => n.to_string(),
        Bool(b) => b.to_string(),
        Ident(s) => s.clone(),
        None => "null".into(),
        _ => "/* expr */".into(),
    }
}

fn escape(s: &str) -> String { s.replace('\\', "\\\\").replace('"', "\\\"") }
