use crate::axir::build::{Ir, IrNode, IrStmt};
use crate::error::AxResult;
use std::fmt::Write;
use std::path::Path;

pub struct KotlinReport {
    pub files: usize,
    pub unsupported: Vec<String>,
}

/// Generator Android: Jetpack Compose z semantyką dostępności zgodną z IR.
pub fn emit(ir: &Ir, out: &Path, _verbose: bool) -> AxResult<KotlinReport> {
    std::fs::create_dir_all(out)?;
    let mut report = KotlinReport { files: 0, unsupported: vec![] };
    let mut models = String::new();
    writeln!(models, "// Generated by AXCode — modele domenowe").ok();
    writeln!(models, "package app.axbridge\n").ok();
    for model in &ir.models {
        writeln!(models, "data class {} (", model.name).ok();
        for (index, field) in model.fields.iter().enumerate() {
            let comma = if index + 1 < model.fields.len() { "," } else { "" };
            writeln!(models, "    val {}: {}{}", field.name, kotlin_type(&field.ty, field.optional), comma).ok();
        }
        writeln!(models, ")\n").ok();
    }
    std::fs::write(out.join("Models.kt"), models)?;
    report.files += 1;

    let mut screens = String::new();
    writeln!(screens, "// Generated by AXCode — ekrany z dostępnością").ok();
    writeln!(screens, "package app.axbridge\n").ok();
    writeln!(screens, "import androidx.compose.foundation.layout.*").ok();
    writeln!(screens, "import androidx.compose.foundation.rememberScrollState").ok();
    writeln!(screens, "import androidx.compose.foundation.verticalScroll").ok();
    writeln!(screens, "import androidx.compose.material3.*").ok();
    writeln!(screens, "import androidx.compose.runtime.*").ok();
    writeln!(screens, "import androidx.compose.ui.Modifier").ok();
    writeln!(screens, "import androidx.compose.ui.semantics.*").ok();
    writeln!(screens, "import androidx.compose.ui.unit.dp\n").ok();
    for screen in &ir.screens {
        writeln!(screens, "@Composable").ok();
        writeln!(screens, "fun {}Screen(onNavigate: (String) -> Unit = {{}}) {{", screen.name).ok();
        for (name, ty, default) in &screen.states {
            writeln!(screens, "    var {} by remember {{ mutableStateOf({}) }}", name, kotlin_default(ty, default)).ok();
        }
        writeln!(screens, "    Column(").ok();
        writeln!(screens, "        modifier = Modifier\n            .fillMaxSize()\n            .verticalScroll(rememberScrollState())\n            .padding(16.dp),").ok();
        writeln!(screens, "        verticalArrangement = Arrangement.spacedBy(12.dp),").ok();
        writeln!(screens, "    ) {{").ok();
        writeln!(screens, "        Text(" + &kotlin_str(screen.title.as_deref().unwrap_or(&screen.name)) + ", style = MaterialTheme.typography.headlineMedium, modifier = Modifier.semantics {{ heading() }})").ok();
        for node in &screen.nodes {
            emit_node(&mut screens, node, 2, &mut report);
        }
        writeln!(screens, "    }}\n}}\n").ok();
    }
    std::fs::write(out.join("Screens.kt"), screens)?;
    report.files += 1;
    Ok(report)
}

fn emit_node(source: &mut String, node: &IrNode, depth: usize, report: &mut KotlinReport) {
    let pad = "    ".repeat(depth);
    let label = node
        .accessibility_label
        .clone()
        .or_else(|| node.label.clone())
        .or_else(|| node.alt.clone());
    match node.kind.as_str() {
        "column" | "row" => {
            for child in &node.children {
                emit_node(source, child, depth, report);
            }
        }
        "text" => {
            let body = node.label.clone().unwrap_or_default();
            writeln!(source, "{pad}Text({})", kotlin_str(&body)).ok();
        }
        "button" => {
            let body = node.label.clone().unwrap_or_else(|| "Przycisk".into());
            let onClick = node.on_tap.first().map(kotlin_action).unwrap_or_else(|| "{}".into());
            let semantics = label.map(|l| format!("Modifier\n{pad}    .height({}.dp)\n{pad}    .semantics {{ contentDescription = {} }}", node.height.unwrap_or(48.0), kotlin_str(&l))).unwrap_or_else(|| format!("Modifier\n{pad}    .height({}.dp)", node.height.unwrap_or(48.0)));
            writeln!(source, "{pad}Button(onClick = {}, modifier = {}\n{pad}) {{\n{pad}    Text({})\n{pad}}}", onClick, semantics, kotlin_str(&body)).ok();
        }
        "list" => {
            writeln!(source, "{pad}Column(modifier = Modifier.semantics {{ }} , verticalArrangement = Arrangement.spacedBy(8.dp)) {{").ok();
            for child in &node.children {
                emit_node(source, child, depth + 1, report);
            }
            writeln!(source, "{pad}}}").ok();
        }
        "image" => {
            writeln!(source, "{pad}Text({}, modifier = Modifier.semantics {{ contentDescription = {} }})", kotlin_str(node.alt.as_deref().unwrap_or("Obraz")), kotlin_str(node.alt.as_deref().unwrap_or("Obraz"))).ok();
        }
        "confirm" => {
            writeln!(source, "{pad}Column(modifier = Modifier.semantics {{ }} , verticalArrangement = Arrangement.spacedBy(8.dp)) {{").ok();
            for child in &node.children {
                emit_node(source, child, depth + 1, report);
            }
            writeln!(source, "{pad}    Text(\"Wymaga zatwierdzenia przez człowieka.\")").ok();
            writeln!(source, "{pad}}}").ok();
        }
        "timer" => {}
        other => report.unsupported.push(other.to_string()),
    }
}

fn kotlin_action(stmt: &IrStmt) -> String {
    match stmt {
        IrStmt::Go { screen } => format!("{{ onNavigate({}) }}", kotlin_str(screen)),
        IrStmt::Toast(expr) => format!("{{ _ = {} }}", kotlin_expr(expr)),
        _ => "{}".into(),
    }
}

fn kotlin_expr(expr: &crate::ast::Expr) -> String {
    use crate::ast::Expr;
    match expr {
        Expr::Str(value) => kotlin_str(value),
        Expr::Num(value) => format!("{}", value),
        Expr::Bool(value) => format!("{}", value),
        Expr::Ident(name) => name.clone(),
        _ => "\"\"".into(),
    }
}

fn kotlin_type(ty: &str, optional: bool) -> String {
    let base = match ty {
        "Text" => "String",
        "Number" => "Double",
        "Boolean" => "Boolean",
        "Date" => "String",
        other if other.starts_with("List<") => return format!("List<{}>{}", kotlin_type(other.trim_start_matches("List<").trim_end_matches('>'), false), if optional { "?" } else { "" }),
        _ => "String",
    };
    format!("{}{}", base, if optional { "?" } else { "" })
}

fn kotlin_default(ty: &str, default: &str) -> String {
    match ty {
        "Number" => default.parse::<f64>().map(|v| format!("{}", v)).unwrap_or_else(|_| "0.0".into()),
        "Boolean" => if default == "true" { "true".into() } else { "false".into() },
        _ => kotlin_str(default.trim_matches('"')),
    }
}

fn kotlin_str(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\"").replace('$', "\\$"))
}
