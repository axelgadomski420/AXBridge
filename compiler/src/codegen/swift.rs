use crate::axir::build::{Ir, IrNode, IrStmt};
use crate::error::{AxError, AxResult};
use std::fmt::Write;
use std::path::Path;

pub struct SwiftReport {
    pub files: usize,
    pub unsupported: Vec<String>,
}

/// Generator iOS: SwiftUI z semantyką dostępności zgodną z IR.
pub fn emit(ir: &Ir, out: &Path, _verbose: bool) -> AxResult<SwiftReport> {
    std::fs::create_dir_all(out)?;
    let mut report = SwiftReport { files: 0, unsupported: vec![] };
    let mut models = String::new();
    writeln!(models, "// Generated by AXCode — modele domenowe").ok();
    writeln!(models, "import Foundation\n").ok();
    for model in &ir.models {
        writeln!(models, "public struct {}: Codable, Hashable, Sendable {{", model.name).ok();
        for field in &model.fields {
            let ty = swift_type(&field.ty, field.optional);
            writeln!(models, "    public var {}: {}", field.name, ty).ok();
        }
        writeln!(models, "\n    public init(").ok();
        for (index, field) in model.fields.iter().enumerate() {
            let comma = if index + 1 < model.fields.len() { "," } else { "" };
            writeln!(models, "        {}: {}{}", field.name, swift_type(&field.ty, field.optional), comma).ok();
        }
        writeln!(models, "    ) {{").ok();
        for field in &model.fields {
            writeln!(models, "        self.{} = {}", field.name, field.name).ok();
        }
        writeln!(models, "    }}\n}}\n").ok();
    }
    std::fs::write(out.join("Models.swift"), models)?;
    report.files += 1;

    let mut views = String::new();
    writeln!(views, "// Generated by AXCode — widoki z dostępnością").ok();
    writeln!(views, "import SwiftUI\n").ok();
    writeln!(views, "public struct AccessibilityProfile: Codable, Equatable {{").ok();
    writeln!(views, "    public var textScale: Double = 1").ok();
    writeln!(views, "    public var reduceMotion: Bool = false").ok();
    writeln!(views, "    public var highContrast: Bool = false").ok();
    writeln!(views, "    public var morseWpm: Int = 15").ok();
    writeln!(views, "    public var vibrationStrength: Double = 0.7").ok();
    writeln!(views, "    public var confirmBeforeSend: Bool = true").ok();
    writeln!(views, "    public static let `default` = AccessibilityProfile()\n}}\n").ok();
    for screen in &ir.screens {
        writeln!(views, "public struct {}View: View {{", screen.name).ok();
        writeln!(views, "    @Environment(\\.accessibilityReduceMotion) private var reduceMotion").ok();
        writeln!(views, "    @State private var profile = AccessibilityProfile.default").ok();
        for (name, ty, default) in &screen.states {
            writeln!(views, "    @State private var {}: {} = {}", name, swift_type(ty, false), swift_default(ty, default)).ok();
        }
        writeln!(views, "    public var onNavigate: (String) -> Void\n").ok();
        writeln!(views, "    public init(onNavigate: @escaping (String) -> Void = {{ _ in }}) {{ self.onNavigate = onNavigate }}\n").ok();
        writeln!(views, "    public var body: some View {{").ok();
        writeln!(views, "        ScrollView {{").ok();
        writeln!(views, "            VStack(alignment: .leading, spacing: 16) {{").ok();
        writeln!(views, "                Text({}).font(.largeTitle).bold().accessibilityAddTraits(.isHeader)", swift_str(screen.title.as_deref().unwrap_or(&screen.name))).ok();
        for node in &screen.nodes {
            emit_node(&mut views, node, 4, &mut report);
        }
        writeln!(views, "            }}.padding()\n        }}").ok();
        writeln!(views, "        .dynamicTypeSize(.xSmall ... .accessibility3)").ok();
        writeln!(views, "    }}\n}}\n").ok();
    }
    std::fs::write(out.join("Screens.swift"), views)?;
    report.files += 1;
    Ok(report)
}

fn emit_node(source: &mut String, node: &IrNode, depth: usize, report: &mut SwiftReport) {
    let pad = "    ".repeat(depth);
    let label = node
        .accessibility_label
        .clone()
        .or_else(|| node.label.clone())
        .or_else(|| node.alt.clone());
    match node.kind.as_str() {
        "column" | "row" => {
            for child in &node.children {
                emit_node(source, child, depth, report);
            }
        }
        "text" => {
            let body = node.label.clone().unwrap_or_default();
            writeln!(source, "{pad}Text({})", swift_str(&body)).ok();
        }
        "button" => {
            let body = node.label.clone().unwrap_or_else(|| "Przycisk".into());
            let action = node.on_tap.first().map(swift_action).unwrap_or_else(|| "{}".into());
            writeln!(source, "{pad}Button(action: {}) {{\n{pad}    Text({}).frame(minHeight: {})\n{pad}}}", action, swift_str(&body), node.height.unwrap_or(48.0)).ok();
            if let Some(label) = label {
                writeln!(source, "{pad}.accessibilityLabel({})", swift_str(&label)).ok();
            }
        }
        "list" => {
            writeln!(source, "{pad}VStack(alignment: .leading, spacing: 8) {{").ok();
            for child in &node.children {
                emit_node(source, child, depth + 1, report);
            }
            writeln!(source, "{pad}}}.accessibilityElement(children: .contain)").ok();
        }
        "image" => {
            writeln!(source, "{pad}Image(systemName: \"photo\").accessibilityLabel({})", swift_str(node.alt.as_deref().unwrap_or("Obraz"))).ok();
        }
        "confirm" => {
            writeln!(source, "{pad}VStack(alignment: .leading, spacing: 8) {{").ok();
            for child in &node.children {
                emit_node(source, child, depth + 1, report);
            }
            writeln!(source, "{pad}    Text(\"Wymaga zatwierdzenia przez człowieka.\").font(.footnote)").ok();
            writeln!(source, "{pad}}}.accessibilityElement(children: .contain)").ok();
        }
        "timer" => {}
        other => report.unsupported.push(other.to_string()),
    }
}

fn swift_action(stmt: &IrStmt) -> String {
    match stmt {
        IrStmt::Go { screen } => format!("{{ onNavigate({}) }}", swift_str(screen)),
        IrStmt::Toast(expr) => format!("{{ _ = {} }}", swift_expr(expr)),
        _ => "{}".into(),
    }
}

fn swift_expr(expr: &crate::ast::Expr) -> String {
    use crate::ast::Expr;
    match expr {
        Expr::Str(value) => swift_str(value),
        Expr::Num(value) => format!("{}", value),
        Expr::Bool(value) => format!("{}", value),
        Expr::Ident(name) => name.clone(),
        _ => "\"\"".into(),
    }
}

fn swift_type(ty: &str, optional: bool) -> String {
    let base = match ty {
        "Text" => "String",
        "Number" => "Double",
        "Boolean" => "Bool",
        "Date" => "Date",
        other if other.starts_with("List<") => return format!("[{}]{}", swift_type(other.trim_start_matches("List<").trim_end_matches('>'), false), if optional { "?" } else { "" }),
        _ => "String",
    };
    format!("{}{}", base, if optional { "?" } else { "" })
}

fn swift_default(ty: &str, default: &str) -> String {
    match ty {
        "Number" => default.parse::<f64>().map(|v| format!("{}", v)).unwrap_or_else(|_| "0".into()),
        "Boolean" => if default == "true" { "true".into() } else { "false".into() },
        _ => swift_str(default.trim_matches('"')),
    }
}

fn swift_str(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}
