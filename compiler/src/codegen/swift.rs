use crate::axir::Ir;
use crate::error::AxResult;
use std::fmt::Write;
use std::path::Path;

pub fn emit(ir: &Ir, out: &Path, _verbose: bool) -> AxResult<()> {
    let mut s = String::new();
    writeln!(s, "// Generated by AXCode Ultra Compiler").ok();
    writeln!(s, "// App: {} v{}", ir.app.name, ir.app.version).ok();
    writeln!(s, "import SwiftUI\nimport Foundation\nimport CryptoKit\n").ok();

    // Models
    for m in &ir.models {
        writeln!(s, "public struct {}: Codable, Identifiable, Hashable {{", m.name).ok();
        for f in &m.fields {
            writeln!(s, "    public var {}: {}", f.name, swift_type(&f.ty)).ok();
        }
        writeln!(s, "    public var id: String {{ String(describing: self) }}\n").ok();
        writeln!(s, "    public init() {{}}").ok();
        writeln!(s, "}}\n").ok();
    }

    // Stores
    for st in &ir.stores {
        writeln!(s, "public final class {}Store: ObservableObject {{", capitalize(&st.name)).ok();
        writeln!(s, "    @Published public var data: {} = []", st.ty).ok();
        writeln!(s, "    private let key = \"{}\"", st.key).ok();
        writeln!(s, "    public func load() {{ /* load from UserDefaults/Keychain */ }}").ok();
        writeln!(s, "    public func save() {{ /* persist */ }}").ok();
        writeln!(s, "}}\n").ok();
    }

    // Globals
    writeln!(s, "public final class AppState: ObservableObject {{").ok();
    for g in &ir.globals {
        writeln!(s, "    @Published public var {}: {} = {}", g.name, swift_type(&g.ty), swift_default(&g.ty, &g.default)).ok();
    }
    writeln!(s, "}}\n").ok();

    // Functions
    for f in &ir.functions {
        let params = f.params.iter().map(|p| format!("_ {}: {}", p.name, swift_type(&p.ty))).collect::<Vec<_>>().join(", ");
        let ret = f.ret.as_ref().map(|t| format!(" -> {}", swift_type(t))).unwrap_or_default();
        writeln!(s, "public func {}({}){} {{", f.name, params, ret).ok();
        emit_stmts(&mut s, &f.body, 1);
        writeln!(s, "}}\n").ok();
    }

    // Screens as SwiftUI views
    for sc in &ir.screens {
        writeln!(s, "public struct {}View: View {{", sc.name).ok();
        for st in &sc.states {
            writeln!(s, "    @State private var {}: {} = {}", st.name, swift_type(&st.ty), swift_default(&st.ty, &st.default)).ok();
        }
        writeln!(s, "    public init() {{}}").ok();
        writeln!(s, "    public var body: some View {{").ok();
        writeln!(s, "        VStack {{ // {} — {} nodes", sc.name, sc.body.len()).ok();
        for n in &sc.body {
            emit_ui_node(&mut s, n, 3);
        }
        writeln!(s, "        }}").ok();
        writeln!(s, "        .accessibilityElement(children: .contain)").ok();
        writeln!(s, "    }}").ok();
        writeln!(s, "}}\n").ok();
    }

    // Components
    for c in &ir.components {
        writeln!(s, "public struct {}View: View {{", c.name).ok();
        for p in &c.params {
            writeln!(s, "    public let {}: {}", p.name, swift_type(&p.ty)).ok();
        }
        writeln!(s, "    public var body: some View {{").ok();
        writeln!(s, "        VStack {{ // {} components", c.name).ok();
        for n in &c.body { emit_ui_node(&mut s, n, 3); }
        writeln!(s, "        }}").ok();
        writeln!(s, "    }}").ok();
        writeln!(s, "}}\n").ok();
    }

    std::fs::write(out.join("AXBridge.swift"), s)?;
    Ok(())
}

fn emit_ui_node(s: &mut String, n: &crate::ast::Node, depth: usize) {
    let pad = "    ".repeat(depth);
    match n.kind.as_str() {
        "text" => {
            let label = n.attrs.iter().find_map(|(k, v)| if k == "label" { if let crate::ast::PropValue::Str(s) = v { Some(s.clone()) } else { None } } else { None }).unwrap_or_default();
            writeln!(s, "{}Text(\"{}\")", pad, escape(&label)).ok();
        }
        "button" => {
            let label = n.attrs.iter().find_map(|(k, v)| if k == "label" { if let crate::ast::PropValue::Str(s) = v { Some(s.clone()) } else { None } } else { None }).unwrap_or_default();
            writeln!(s, "{}Button(\"{}\") {{ /* action */ }}", pad, escape(&label)).ok();
            writeln!(s, "{}    .frame(minWidth: 44, minHeight: 44)", pad).ok();
        }
        "column" => {
            writeln!(s, "{}VStack(alignment: .leading) {{", pad).ok();
            for c in &n.children { emit_ui_node(s, c, depth + 1); }
            writeln!(s, "{}}}", pad).ok();
        }
        "row" => {
            writeln!(s, "{}HStack {{", pad).ok();
            for c in &n.children { emit_ui_node(s, c, depth + 1); }
            writeln!(s, "{}}}", pad).ok();
        }
        "image" => {
            let label = n.attrs.iter().find_map(|(k, v)| if k == "label" || k == "alt" { if let crate::ast::PropValue::Str(s) = v { Some(s.clone()) } else { None } } else { None }).unwrap_or_default();
            writeln!(s, "{}Image(\"{}\").accessibilityLabel(\"{}\")", pad, "placeholder", escape(&label)).ok();
        }
        "field" => {
            writeln!(s, "{}TextField(\"\", text: .constant(\"\"))", pad).ok();
            writeln!(s, "{}    .frame(minHeight: 44)", pad).ok();
        }
        "spinner" => writeln!(s, "{}ProgressView()", pad).ok(),
        "divider" => writeln!(s, "{}Divider()", pad).ok(),
        "spacer" => writeln!(s, "{}Spacer()", pad).ok(),
        other => {
            writeln!(s, "{}// TODO: node '{}'", pad, other).ok();
            for c in &n.children { emit_ui_node(s, c, depth); }
        }
    }
}

fn emit_stmts(s: &mut String, stmts: &[crate::ast::Stmt], depth: usize) {
    let pad = "    ".repeat(depth);
    for stmt in stmts {
        match stmt {
            crate::ast::Stmt::Set { target, value } => writeln!(s, "{}{} = {}", pad, target, expr_str(value)).ok(),
            crate::ast::Stmt::Add { value, target } => writeln!(s, "{}{}.append({})", pad, target, expr_str(value)).ok(),
            crate::ast::Stmt::ShowToast(e) => writeln!(s, "{}print(\"[toast] \" + ({}))", pad, expr_str(e)).ok(),
            crate::ast::Stmt::If { cond, then, els } => {
                writeln!(s, "{}if {} {{", pad, expr_str(cond)).ok();
                emit_stmts(s, then, depth + 1);
                if !els.is_empty() {
                    writeln!(s, "{}}} else {{", pad).ok();
                    emit_stmts(s, els, depth + 1);
                }
                writeln!(s, "{}}}", pad).ok();
            }
            _ => writeln!(s, "{}// stmt", pad).ok(),
        }
    }
}

fn expr_str(e: &crate::ast::Expr) -> String {
    use crate::ast::Expr::*;
    match e {
        Str(s) => format!("\"{}\"", s),
        Num(n) => n.to_string(),
        Bool(b) => b.to_string(),
        Ident(s) => s.clone(),
        Field(b, f) => format!("{}.{}", expr_str(b), f),
        Call(b, args) => format!("{}({})", expr_str(b), args.iter().map(expr_str).collect::<Vec<_>>().join(", ")),
        None => "nil".into(),
        _ => "/* expr */".into(),
    }
}

fn swift_type(t: &crate::ast::TypeRef) -> String {
    use crate::ast::TypeRef::*;
    match t {
        Text => "String".into(),
        Number => "Double".into(),
        Boolean => "Bool".into(),
        Date => "Date".into(),
        Json => "[String: Any]".into(),
        List(inner) => format!("[{}]", swift_type(inner)),
        Map(inner) => format!("[String: {}]", swift_type(inner)),
        Optional(inner) => format!("{}?", swift_type(inner)),
        Named(n) => n.clone(),
    }
}

fn swift_default(t: &crate::ast::TypeRef, d: &str) -> String {
    if !d.is_empty() { return d.into(); }
    use crate::ast::TypeRef::*;
    match t {
        Text => "\"\"".into(),
        Number => "0".into(),
        Boolean => "false".into(),
        Optional(_) => "nil".into(),
        List(_) => "[]".into(),
        _ => "Date()".into(),
    }
}

fn capitalize(s: &str) -> String {
    let mut c = s.chars();
    match c.next() { Some(f) => f.to_uppercase().collect::<String>() + c.as_str(), None => String::new() }
}

fn escape(s: &str) -> String { s.replace('\\', "\\\\").replace('"', "\\\"") }
