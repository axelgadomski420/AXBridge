use crate::axir::Ir;
use crate::error::AxResult;
use std::fmt::Write;
use std::path::Path;

pub fn emit(ir: &Ir, out: &Path, _verbose: bool) -> AxResult<()> {
    let mut s = String::new();
    writeln!(s, "// Generated by AXCode Ultra Compiler").ok();
    writeln!(s, "// App: {} v{}", ir.app.name, ir.app.version).ok();
    writeln!(s, "import {{ useState, useEffect }} from 'react';\n").ok();

    for m in &ir.models {
        writeln!(s, "export interface {} {{", m.name).ok();
        for f in &m.fields {
            writeln!(s, "  {}: {};", f.name, ts_type(&f.ty)).ok();
        }
        writeln!(s, "}}\n").ok();
    }

    for st in &ir.stores {
        writeln!(s, "export class {}Store {{", cap(&st.name)).ok();
        writeln!(s, "  key = '{}';", st.key).ok();
        writeln!(s, "  data: {}[] = [];", st.ty).ok();
        writeln!(s, "  load() {{ try {{ this.data = JSON.parse(localStorage.getItem(this.key) || '[]'); }} catch {{}} }}").ok();
        writeln!(s, "  save() {{ localStorage.setItem(this.key, JSON.stringify(this.data)); }}").ok();
        writeln!(s, "}}\n").ok();
    }

    for f in &ir.functions {
        let params = f.params.iter().map(|p| format!("{}: {}", p.name, ts_type(&p.ty))).collect::<Vec<_>>().join(", ");
        let ret = f.ret.as_ref().map(|t| format!(": {}", ts_type(t))).unwrap_or_default();
        writeln!(s, "export function {}({}){} {{", f.name, params, ret).ok();
        for st in &f.body {
            if let crate::ast::Stmt::Set { target, value } = st {
                writeln!(s, "  {} = {};", target, expr_str(value)).ok();
            }
        }
        writeln!(s, "}}\n").ok();
    }

    for sc in &ir.screens {
        writeln!(s, "export function {}Screen() {{", sc.name).ok();
        for st in &sc.states {
            writeln!(s, "  const [{}, set{}] = useState({});", st.name, cap(&st.name), ts_default(&st.ty, &st.default)).ok();
        }
        writeln!(s, "  return (").ok();
        writeln!(s, "    <div role=\"main\" aria-label=\"{}\">", sc.title.as_deref().unwrap_or(&sc.name)).ok();
        for n in &sc.body { emit_ui_node(&mut s, n, 3); }
        writeln!(s, "    </div>").ok();
        writeln!(s, "  );").ok();
        writeln!(s, "}}\n").ok();
    }

    std::fs::write(out.join("axbridge.tsx"), s)?;
    Ok(())
}

fn emit_ui_node(s: &mut String, n: &crate::ast::Node, depth: usize) {
    let pad = "  ".repeat(depth);
    match n.kind.as_str() {
        "text" => {
            let label = n.attrs.iter().find_map(|(k, v)| if k == "label" { if let crate::ast::PropValue::Str(s) = v { Some(s.clone()) } else { None } } else { None }).unwrap_or_default();
            writeln!(s, "{}<p>{}</p>", pad, esc(&label)).ok();
        }
        "button" => {
            let label = n.attrs.iter().find_map(|(k, v)| if k == "label" { if let crate::ast::PropValue::Str(s) = v { Some(s.clone()) } else { None } } else { None }).unwrap_or_default();
            writeln!(s, "{}<button aria-label=\"{}\" style={{{{ minWidth: 48, minHeight: 48 }}}}>{}</button>", pad, esc(&label), esc(&label)).ok();
        }
        "column" => {
            writeln!(s, "{}<div style={{{{ display: 'flex', flexDirection: 'column' }}}}>", pad).ok();
            for c in &n.children { emit_ui_node(s, c, depth + 1); }
            writeln!(s, "{}</div>", pad).ok();
        }
        "row" => {
            writeln!(s, "{}<div style={{{{ display: 'flex', flexDirection: 'row' }}}}>", pad).ok();
            for c in &n.children { emit_ui_node(s, c, depth + 1); }
            writeln!(s, "{}</div>", pad).ok();
        }
        "field" => writeln!(s, "{}<input aria-label=\"pole\" />", pad).ok(),
        "spinner" => writeln!(s, "{}<div role=\"progressbar\">…</div>", pad).ok(),
        other => { writeln!(s, "{{/* TODO: {} */}}", other).ok(); }
    }
}

fn ts_type(t: &crate::ast::TypeRef) -> String {
    use crate::ast::TypeRef::*;
    match t {
        Text => "string".into(),
        Number => "number".into(),
        Boolean => "boolean".into(),
        Date => "Date".into(),
        Json => "Record<string, unknown>".into(),
        List(i) => format!("{}[]", ts_type(i)),
        Map(i) => format!("Record<string, {}>", ts_type(i)),
        Optional(i) => format!("{} | null", ts_type(i)),
        Named(n) => n.clone(),
    }
}

fn ts_default(t: &crate::ast::TypeRef, d: &str) -> String {
    if !d.is_empty() { return d.into(); }
    use crate::ast::TypeRef::*;
    match t {
        Text => "''".into(),
        Number => "0".into(),
        Boolean => "false".into(),
        Optional(_) => "null".into(),
        List(_) => "[]".into(),
        _ => "new Date()".into(),
    }
}

fn expr_str(e: &crate::ast::Expr) -> String {
    use crate::ast::Expr::*;
    match e {
        Str(s) => format!("'{}'", s.replace('\'', "\\'")),
        Num(n) => n.to_string(),
        Bool(b) => b.to_string(),
        Ident(s) => s.clone(),
        None => "null".into(),
        _ => "undefined".into(),
    }
}

fn cap(s: &str) -> String {
    let mut c = s.chars();
    match c.next() { Some(f) => f.to_uppercase().collect::<String>() + c.as_str(), None => String::new() }
}

fn esc(s: &str) -> String { s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;").replace('"', "&quot;") }
