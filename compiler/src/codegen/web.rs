use crate::axir::build::{Ir, IrNode, IrStmt};
use crate::error::AxResult;
use std::fmt::Write;
use std::path::Path;

/// Generator Web: TypeScript, React i ARIA. Emituje każdy węzeł IR —
/// brak cichego pomijania konstrukcji, każdy unsupported node trafia do raportu.
pub struct WebReport {
    pub screens: usize,
    pub nodes: usize,
    pub unsupported: Vec<String>,
}

pub fn emit(ir: &Ir, out: &Path, _verbose: bool) -> AxResult<WebReport> {
    std::fs::create_dir_all(out)?;
    let mut report = WebReport { screens: ir.screens.len(), nodes: 0, unsupported: vec![] };
    let mut source = String::new();
    writeln!(source, "// Generated by AXCode — dostępność jest częścią kontraktu, nie dodatkiem.").ok();
    writeln!(source, "import React, {{ useEffect, useRef, useState }} from 'react';").ok();
    writeln!(source, "import {{ announce, applyAccessibilityProfile, haptic, speak }} from './ax.runtime.js';\n").ok();

    for model in &ir.models {
        writeln!(source, "export interface {} {{", model.name).ok();
        for field in &model.fields {
            let ty = if field.optional { format!("{} | null", ts_type(&field.ty)) } else { ts_type(&field.ty) };
            writeln!(source, "  {}: {};", field.name, ty).ok();
        }
        writeln!(source, "}}\n").ok();
    }

    for store in &ir.stores {
        writeln!(source, "export const {}Store = {{", cap(&store.name)).ok();
        writeln!(source, "  key: {},", json_str(&store.key)).ok();
        writeln!(source, "  kind: {},", json_str(&store.kind)).ok();
        writeln!(source, "  encrypted: {},", store.encrypted).ok();
        writeln!(source, "  read<T>(): T[] {{ try {{ const raw = localStorage.getItem(this.key); return raw ? (JSON.parse(raw) as T[]) : []; }} catch {{ return []; }} }},").ok();
        writeln!(source, "  write<T>(items: T[]) {{ localStorage.setItem(this.key, JSON.stringify(items)); }},").ok();
        writeln!(source, "  clear() {{ localStorage.removeItem(this.key); }},\n}};\n").ok();
    }

    for function in &ir.functions {
        let params = function
            .params
            .iter()
            .map(|(name, ty)| format!("{}: {}", name, ts_type(ty)))
            .collect::<Vec<_>>()
            .join(", ");
        let ret = function.ret.as_ref().map(|t| format!(": {}", ts_type(t))).unwrap_or_default();
        writeln!(source, "export function {}({}){} {{", function.name, params, ret).ok();
        for stmt in &function.body {
            emit_stmt(&mut source, stmt, 1, &mut report);
        }
        writeln!(source, "}}\n").ok();
    }

    for screen in &ir.screens {
        writeln!(source, "export function {}Screen({{ onNavigate }}: {{ onNavigate: (screen: string) => void }}) {{", screen.name).ok();
        for (name, ty, default) in &screen.states {
            writeln!(source, "  const [{}, set{}] = useState<{}>({});", name, cap(name), ts_type(ty), ts_default(ty, default)).ok();
        }
        writeln!(source, "  const headingRef = useRef<HTMLHeadingElement>(null);").ok();
        writeln!(source, "  useEffect(() => {{ headingRef.current?.focus(); announce({}); }}, []);", json_str(screen.title.as_deref().unwrap_or(&screen.name))).ok();
        writeln!(source, "  return (").ok();
        writeln!(source, "    <>").ok();
        writeln!(source, "      <h1 ref={{headingRef}} tabIndex={{-1}}>{}</h1>", escape(screen.title.as_deref().unwrap_or(&screen.name))).ok();
        for node in &screen.nodes {
            emit_node(&mut source, node, 3, &mut report);
        }
        writeln!(source, "    </>").ok();
        writeln!(source, "  );\n}}\n").ok();
    }

    writeln!(source, "export const screens = {{ {} }};", ir.screens.iter().map(|s| format!("{0}: {0}Screen", s.name)).collect::<Vec<_>>().join(", ")).ok();

    std::fs::write(out.join("ax.app.tsx"), source)?;
    std::fs::write(out.join("ax.runtime.js"), include_str!("templates/ax-runtime.js"))?;
    let shell = include_str!("templates/accessible-shell.html")
        .replace("{{APP_NAME}}", &ir.app.name)
        .replace("{{LANG}}", &ir.app.language)
        .replace("{{TEXT_SCALE}}", &format!("{}", ir.app.text_scale))
        .replace("{%ROOT_ATTRS%}", "")
        .replace("{%ROOT_STYLE%}", "");
    std::fs::write(out.join("index.html"), shell)?;
    Ok(report)
}

fn emit_node(source: &mut String, node: &IrNode, depth: usize, report: &mut WebReport) {
    report.nodes += 1;
    let pad = "  ".repeat(depth);
    let label = node
        .accessibility_label
        .clone()
        .or_else(|| node.label.clone())
        .or_else(|| node.alt.clone());
    let aria = label.map(|l| format!(" aria-label={}", json_str(&l))).unwrap_or_default();
    let live = node.aria_live.as_ref().map(|p| format!(" aria-live={}", json_str(p))).unwrap_or_default();

    match node.kind.as_str() {
        "column" | "row" => {
            let role = if node.kind == "row" { "group" } else { "region" };
            writeln!(source, "{pad}<div role={} className=\"card\"{}>", json_str(role), aria).ok();
            for child in &node.children {
                emit_node(source, child, depth + 1, report);
            }
            writeln!(source, "{pad}</div>").ok();
        }
        "list" => {
            writeln!(source, "{pad}<ul role=\"list\"{}>", live).ok();
            for child in &node.children {
                emit_node(source, child, depth + 1, report);
            }
            writeln!(source, "{pad}</ul>").ok();
        }
        "item" => {
            writeln!(source, "{pad}<li>").ok();
            for child in &node.children {
                emit_node(source, child, depth + 1, report);
            }
            writeln!(source, "{pad}</li>").ok();
        }
        "text" => {
            let body = node.label.clone().unwrap_or_default();
            writeln!(source, "{pad}<p>{}</p>", escape(&body)).ok();
        }
        "button" => {
            let body = node.label.clone().unwrap_or_else(|| "Przycisk".into());
            let handler = node.on_tap.first().map(render_handler).unwrap_or_else(|| "() => {}".into());
            writeln!(source, "{pad}<button type=\"button\" onClick={{{}}} style={{{{ minHeight: {} }}}}{}{}>{}</button>", handler, node.height.unwrap_or(48.0), aria, escape(&body)).ok();
        }
        "image" => {
            writeln!(source, "{pad}<img alt={} src={{placeholder}} />", json_str(node.alt.as_deref().unwrap_or(""))).ok();
        }
        "toggle" => {
            writeln!(source, "{pad}<button type=\"button\" role=\"switch\" aria-checked={{false}} style={{{{ minHeight: 48 }}}} aria-label=\"Przełącznik\">Przełącz</button>").ok();
        }
        "confirm" => {
            writeln!(source, "{pad}<section role=\"alertdialog\" aria-modal=\"false\"{}>", aria).ok();
            for child in &node.children {
                emit_node(source, child, depth + 1, report);
            }
            writeln!(source, "{pad}  <p className=\"caption\">Wymaga zatwierdzenia przez człowieka.</p>").ok();
            writeln!(source, "{pad}</section>").ok();
        }
        "timer" => {
            writeln!(source, "{pad}{{/* timer obsługiwany przez ax.runtime */}}").ok();
        }
        other => report.unsupported.push(other.to_string()),
    }
}

fn emit_stmt(source: &mut String, stmt: &IrStmt, depth: usize, report: &mut WebReport) {
    let pad = "  ".repeat(depth);
    match stmt {
        IrStmt::Set { target, value } => {
            writeln!(source, "{pad}set{}({});", cap(target.split('.').next().unwrap_or(target)), expr_js(value)).ok();
        }
        IrStmt::Save { target } => writeln!(source, "{pad}void saveStore({});", json_str(target)).ok(),
        IrStmt::Load { target } => writeln!(source, "{pad}void loadStore({});", json_str(target)).ok(),
        IrStmt::Go { screen } => writeln!(source, "{pad}onNavigate({});", json_str(screen)).ok(),
        IrStmt::GoBack => writeln!(source, "{pad}onNavigate('__back');").ok(),
        IrStmt::Toast(expr) => writeln!(source, "{pad}announce({});", expr_js(expr)).ok(),
        IrStmt::Alert(expr) => writeln!(source, "{pad}window.alert({});", expr_js(expr)).ok(),
        IrStmt::Api { path, method, on_error, .. } => {
            writeln!(source, "{pad}try {{").ok();
            writeln!(source, "{pad}  await fetch({}, {{ method: {} }});", json_str(path), json_str(method)).ok();
            writeln!(source, "{pad}}} catch {{").ok();
            for inner in on_error {
                emit_stmt(source, inner, depth + 1, report);
            }
            writeln!(source, "{pad}}}").ok();
        }
        IrStmt::CallFn { name, args } => {
            let rendered = args.iter().map(expr_js).collect::<Vec<_>>().join(", ");
            writeln!(source, "{pad}void {}({});", name, rendered).ok();
        }
        IrStmt::If { cond, then, els } => {
            writeln!(source, "{pad}if ({}) {{", expr_js(cond)).ok();
            for inner in then {
                emit_stmt(source, inner, depth + 1, report);
            }
            if els.is_empty() {
                writeln!(source, "{pad}}}").ok();
            } else {
                writeln!(source, "{pad}}} else {{").ok();
                for inner in els {
                    emit_stmt(source, inner, depth + 1, report);
                }
                writeln!(source, "{pad}}}").ok();
            }
        }
        IrStmt::ForEach { var, iter, body } => {
            writeln!(source, "{pad}for (const {} of {}) {{", var, expr_js(iter)).ok();
            for inner in body {
                emit_stmt(source, inner, depth + 1, report);
            }
            writeln!(source, "{pad}}}").ok();
        }
        IrStmt::Add { target, value } => writeln!(source, "{pad}{}.push({});", target, expr_js(value)).ok(),
        IrStmt::Remove { target, value } => writeln!(source, "{pad}{} = {}.filter(x => x !== {});", target, target, expr_js(value)).ok(),
        IrStmt::Return(Some(expr)) => writeln!(source, "{pad}return {};", expr_js(expr)).ok(),
        IrStmt::Return(None) => {}
    }
}

fn render_handler(stmt: &IrStmt) -> String {
    match stmt {
        IrStmt::Go { screen } => format!("() => onNavigate({})", json_str(screen)),
        IrStmt::Toast(expr) => format!("() => announce({})", expr_js(expr)),
        IrStmt::Api { path, method, .. } => format!("() => void fetch({}, {{ method: {} }})", json_str(path), json_str(method)),
        IrStmt::CallFn { name, .. } => format!("() => void {}()", name),
        _ => "() => {}".into(),
    }
}

fn expr_js(expr: &crate::ast::Expr) -> String {
    use crate::ast::{BinOp, Expr};
    match expr {
        Expr::Str(value) => json_str(value),
        Expr::Num(value) => format!("{}", value),
        Expr::Bool(value) => format!("{}", value),
        Expr::Ident(name) => name.clone(),
        Expr::Field(base, field) => format!("{}.{}", expr_js(base), field),
        Expr::Call(base, args) => format!("{}({})", expr_js(base), args.iter().map(expr_js).collect::<Vec<_>>().join(", ")),
        Expr::BinOp(left, op, right) => {
            let symbol = match op {
                BinOp::Add => "+", BinOp::Sub => "-", BinOp::Mul => "*", BinOp::Div => "/",
                BinOp::Eq => "===", BinOp::Ne => "!==", BinOp::Lt => "<", BinOp::Le => "<=",
                BinOp::Gt => ">", BinOp::Ge => ">=", BinOp::And => "&&", BinOp::Or => "||",
            };
            format!("({} {} {})", expr_js(left), symbol, expr_js(right))
        }
        Expr::UnOp(op, inner) => match op {
            crate::ast::UnOp::Not => format!("(!{})", expr_js(inner)),
            crate::ast::UnOp::Neg => format!("(-{})", expr_js(inner)),
        },
        Expr::Constructor { fields, .. } => format!(
            "{{{}}}",
            fields.iter().map(|(k, v)| format!("{}: {}", k, expr_js(v))).collect::<Vec<_>>().join(", ")
        ),
        Expr::None => "null".into(),
    }
}

fn ts_type(ty: &str) -> String {
    match ty {
        "Text" => "string".into(),
        "Number" => "number".into(),
        "Boolean" => "boolean".into(),
        "Date" => "string".into(),
        other if other.starts_with("List<") => format!("Array<{}>", ts_type(other.trim_start_matches("List<").trim_end_matches('>'))),
        other if other.starts_with("Map<") => format!("Record<string, {}>", ts_type(other.trim_start_matches("Map<").trim_end_matches('>'))),
        other => other.into(),
    }
}

fn ts_default(ty: &str, default: &str) -> String {
    match ty {
        "Number" => default.parse::<f64>().map(|v| format!("{}", v)).unwrap_or_else(|_| "0".into()),
        "Boolean" => if default == "true" { "true".into() } else { "false".into() },
        "Text" => json_str(default.trim_matches('"')),
        _ => "null".into(),
    }
}

fn cap(value: &str) -> String {
    let mut chars = value.chars();
    match chars.next() {
        Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
        None => String::new(),
    }
}

fn json_str(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\"").replace('\n', "\\n"))
}

fn escape(value: &str) -> String {
    value.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;")
}
