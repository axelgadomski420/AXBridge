use crate::axir::build::{Ir, IrModel};
use crate::error::AxResult;
use std::fmt::Write;
use std::path::Path;

pub struct WorkersReport {
    pub files: usize,
    pub unsupported: Vec<String>,
}

/// Generator Workers: schemat D1 z relacjami oraz trasy modeli z autoryzacją.
pub fn emit(ir: &Ir, out: &Path, _verbose: bool) -> AxResult<WorkersReport> {
    std::fs::create_dir_all(out)?;
    let mut report = WorkersReport { files: 0, unsupported: vec![] };

    let mut schema = String::new();
    writeln!(schema, "-- Generated by AXCode — D1 schema").ok();
    writeln!(schema, "PRAGMA foreign_keys=ON;\n").ok();
    for model in &ir.models {
        let table = to_snake(&model.name);
        writeln!(schema, "CREATE TABLE IF NOT EXISTS {} (", table).ok();
        writeln!(schema, "  id TEXT PRIMARY KEY,").ok();
        for field in &model.fields {
            if field.name == "id" {
                continue;
            }
            writeln!(schema, "  {} {}{},", to_snake(&field.name), sql_type(&field.ty), if field.optional { "" } else { " NOT NULL" }).ok();
        }
        writeln!(schema, "  created_at TEXT NOT NULL DEFAULT (datetime('now'))").ok();
        writeln!(schema, ");").ok();
        writeln!(schema, "CREATE INDEX IF NOT EXISTS idx_{}_created ON {}(created_at DESC);\n", table, table).ok();
    }
    std::fs::write(out.join("schema.sql"), schema)?;
    report.files += 1;

    let mut worker = String::new();
    writeln!(worker, "// Generated by AXCode — Cloudflare Worker").ok();
    writeln!(worker, "import {{ auth, body, error, fail, json, rate }} from './core.js';\n").ok();
    writeln!(worker, "export interface Env {{").ok();
    writeln!(worker, "  DB: D1Database; BUCKET: R2Bucket; KV: KVNamespace; AI: Ai; QUEUE: Queue;").ok();
    writeln!(worker, "}}\n").ok();
    writeln!(worker, "export default {{").ok();
    writeln!(worker, "  async fetch(request: Request, env: Env): Promise<Response> {{").ok();
    writeln!(worker, "    const url = new URL(request.url);").ok();
    writeln!(worker, "    try {{").ok();
    writeln!(worker, "      if (url.pathname === '/health') return json(env, request, {{ ok: true, app: {} }});", ts_str(&ir.app.name)).ok();
    for model in &ir.models {
        emit_model_routes(&mut worker, model);
    }
    writeln!(worker, "      return fail(404, 'NOT_FOUND', 'Endpoint not found');").ok();
    writeln!(worker, "    }} catch (e) {{ return error(env, request, e); }}").ok();
    writeln!(worker, "  }},\n}};\n").ok();
    std::fs::write(out.join("worker.ts"), worker)?;
    report.files += 1;
    Ok(report)
}

fn emit_model_routes(worker: &mut String, model: &IrModel) {
    let table = to_snake(&model.name);
    let columns: Vec<String> = model
        .fields
        .iter()
        .map(|field| to_snake(&field.name))
        .filter(|name| name != "id")
        .collect();
    let column_list = columns.join(",");

    writeln!(worker, "      if (url.pathname === '/api/{0}' && request.method === 'GET') {{", table).ok();
    writeln!(worker, "        const user = await auth(env, request);").ok();
    writeln!(worker, "        await rate(env, user.id, 'read', 120);").ok();
    writeln!(worker, "        const rows = await env.DB.prepare('SELECT * FROM {0} ORDER BY created_at DESC LIMIT 100').all();", table).ok();
    writeln!(worker, "        return json(env, request, {{ rows: rows.results }});").ok();
    writeln!(worker, "      }}").ok();

    writeln!(worker, "      if (url.pathname === '/api/{0}' && request.method === 'POST') {{", table).ok();
    writeln!(worker, "        const user = await auth(env, request);").ok();
    writeln!(worker, "        await rate(env, user.id, 'write', 60);").ok();
    writeln!(worker, "        const input = await body(request) as Record<string, unknown>;").ok();
    writeln!(worker, "        const id = crypto.randomUUID();").ok();
    writeln!(worker, "        const columns = {};", ts_str(&column_list)).ok();
    writeln!(worker, "        const sql = `INSERT INTO {0} (id, ${{columns}}) VALUES (?, ${{columns.split(',').map(() => '?').join(',')}})`;", table).ok();
    writeln!(worker, "        await env.DB.prepare(sql).bind(id, ...columns.split(',').map((c) => input[c])).run();").ok();
    writeln!(worker, "        return json(env, request, {{ id }}, 201);").ok();
    writeln!(worker, "      }}").ok();
}

fn sql_type(ty: &str) -> &'static str {
    match ty {
        "Number" => "REAL",
        "Boolean" => "INTEGER",
        _ => "TEXT",
    }
}

fn to_snake(value: &str) -> String {
    let mut out = String::new();
    for (index, ch) in value.chars().enumerate() {
        if ch.is_uppercase() {
            if index > 0 {
                out.push('_');
            }
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push(ch);
        }
    }
    out
}

fn ts_str(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}
