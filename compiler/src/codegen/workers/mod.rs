use crate::axir::Ir;
use crate::error::AxResult;
use std::fmt::Write;
use std::path::Path;

pub fn emit(ir: &Ir, out: &Path, _verbose: bool) -> AxResult<()> {
    std::fs::create_dir_all(out)?;

    // D1 schema
    let mut schema = String::new();
    writeln!(schema, "-- Generated by AXCode Ultra Compiler — D1 schema").ok();
    for m in &ir.models {
        let table = to_snake(&m.name);
        writeln!(schema, "CREATE TABLE IF NOT EXISTS {} (", table).ok();
        writeln!(schema, "  id TEXT PRIMARY KEY,").ok();
        for f in &m.fields {
            if f.name == "id" { continue; }
            writeln!(schema, "  {} {},", to_snake(&f.name), sql_type(&f.ty)).ok();
        }
        writeln!(schema, "  created_at TEXT NOT NULL DEFAULT (datetime('now'))").ok();
        writeln!(schema, ");").ok();
        writeln!(schema, "CREATE INDEX IF NOT EXISTS idx_{}_created ON {}(created_at DESC);\n", table, table).ok();
    }
    std::fs::write(out.join("schema.sql"), schema)?;

    // Worker
    let mut w = String::new();
    writeln!(w, "// Generated by AXCode Ultra Compiler — Cloudflare Worker").ok();
    writeln!(w, "export interface Env {{").ok();
    writeln!(w, "  DB: D1Database; BUCKET: R2Bucket; KV: KVNamespace; AI: Ai; QUEUE: Queue;").ok();
    writeln!(w, "}}\n").ok();
    writeln!(w, "export default {{").ok();
    writeln!(w, "  async fetch(req: Request, env: Env, ctx: ExecutionContext): Promise<Response> {{").ok();
    writeln!(w, "    const url = new URL(req.url);").ok();
    writeln!(w, "    if (url.pathname === '/health') return Response.json({{ ok: true, app: '{}' }});", ir.app.name).ok();
    for m in &ir.models {
        let table = to_snake(&m.name);
        writeln!(w, "    if (url.pathname === '/api/{0}s' && req.method === 'GET') {{", table).ok();
        writeln!(w, "      const r = await env.DB.prepare('SELECT * FROM {0} LIMIT 100').all();", table).ok();
        writeln!(w, "      return Response.json(r.results);").ok();
        writeln!(w, "    }}").ok();
        writeln!(w, "    if (url.pathname === '/api/{0}s' && req.method === 'POST') {{", table).ok();
        writeln!(w, "      const body = await req.json() as Record<string, unknown>;").ok();
        writeln!(w, "      const id = crypto.randomUUID();").ok();
        writeln!(w, "      const cols = Object.keys(body);").ok();
        writeln!(w, "      const sql = `INSERT INTO {0} (id, ${{cols.join(',')}}) VALUES (?, ${{cols.map(() => '?').join(',')}})`;", table).ok();
        writeln!(w, "      await env.DB.prepare(sql).bind(id, ...cols.map(c => body[c])).run();").ok();
        writeln!(w, "      return Response.json({{ id }});").ok();
        writeln!(w, "    }}").ok();
    }
    // Emergency endpoints (spec-compliant)
    writeln!(w, "    if (url.pathname === '/api/emergency/trigger' && req.method === 'POST') {{").ok();
    writeln!(w, "      const body = await req.json() as any;").ok();
    writeln!(w, "      if (body.confirmed !== true) return Response.json({{ error: 'E_NOT_CONFIRMED' }}, {{ status: 400 }});").ok();
    writeln!(w, "      const duration = body.durationSeconds;").ok();
    writeln!(w, "      if (![900, 1800, 3600].includes(duration)) return Response.json({{ error: 'E_INVALID_DURATION' }}, {{ status: 400 }});").ok();
    writeln!(w, "      const id = crypto.randomUUID();").ok();
    writeln!(w, "      const expiresAt = new Date(Date.now() + duration * 1000).toISOString();").ok();
    writeln!(w, "      await env.DB.prepare('INSERT INTO emergency_events (id, user_id, expires_at, location_precision) VALUES (?, ?, ?, ?)').bind(id, body.userId ?? 'anon', expiresAt, body.payload?.precision ?? 'approximate').run();").ok();
    writeln!(w, "      return Response.json({{ eventId: id, expiresAt }});").ok();
    writeln!(w, "    }}").ok();
    writeln!(w, "    return new Response('Not Found', {{ status: 404 }});").ok();
    writeln!(w, "  }},").ok();
    writeln!(w, "}};").ok();
    std::fs::write(out.join("worker.ts"), w)?;

    // wrangler.toml
    let mut wr = String::new();
    writeln!(wr, "name = \"axbridge-worker\"").ok();
    writeln!(wr, "main = \"worker.ts\"").ok();
    writeln!(wr, "compatibility_date = \"2025-01-01\"\n").ok();
    writeln!(wr, "[[d1_databases]]").ok();
    writeln!(wr, "binding = \"DB\"").ok();
    writeln!(wr, "database_name = \"axbridge\"").ok();
    writeln!(wr, "database_id = \"REPLACE_ME\"\n").ok();
    writeln!(wr, "[[r2_buckets]]").ok();
    writeln!(wr, "binding = \"BUCKET\"").ok();
    writeln!(wr, "bucket_name = \"axbridge-media\"\n").ok();
    writeln!(wr, "[[kv_namespaces]]").ok();
    writeln!(wr, "binding = \"KV\"").ok();
    writeln!(wr, "id = \"REPLACE_ME\"").ok();
    std::fs::write(out.join("wrangler.toml"), wr)?;
    Ok(())
}

fn to_snake(s: &str) -> String {
    let mut out = String::new();
    for (i, c) in s.chars().enumerate() {
        if c.is_uppercase() && i > 0 { out.push('_'); }
        out.push(c.to_lowercase().next().unwrap_or(c));
    }
    out
}

fn sql_type(t: &crate::ast::TypeRef) -> &'static str {
    use crate::ast::TypeRef::*;
    match t {
        Text => "TEXT",
        Number => "REAL",
        Boolean => "INTEGER",
        Date => "TEXT",
        Json => "TEXT",
        List(_) | Map(_) => "TEXT",
        Optional(inner) => sql_type(inner),
        Named(_) => "TEXT",
    }
}
